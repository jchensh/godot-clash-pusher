"""王塔（4×4 格占位）：石砌方塔 + 四角石柱 + 城垛 + 顶部木平台 + 木门；阵营色部件 = 正面王冠旗帜与塔顶旗。
原画：testAssets/新风格美术资源0830/战斗/王塔.png（俯视 3/4）；侧背面为补全设计。1 米 = 1 格，原点在底面中心。
"""

STONE = "#ddd5c4"
STONE_D = "#bdb3a0"
STONE_DD = "#9c927f"
WOOD = "#b27b45"
WOOD_D = "#7d5230"
GOLD = "#f6c343"
TEAM = "#ffffff"   # 阵营色由 Godot 侧按 tint 染（M_Team）


def build(k):
    b = "root"
    k.box(b, (0, 0, 0.15), (3.8, 3.8, 0.3), STONE_DD, bevel=0.3)
    k.box(b, (0, 0, 1.6), (3.1, 3.1, 2.6), STONE, bevel=0.06)
    for x in (-1, 1):
        for y in (-1, 1):
            k.box(b, (1.45 * x, 1.45 * y, 1.75), (0.75, 0.75, 3.1), STONE_D, bevel=0.12)
            k.box(b, (1.45 * x, 1.45 * y, 3.4), (0.9, 0.9, 0.35), STONE_D, bevel=0.15)
    # 墙面石块点缀（四面错落）
    for (x, y, z, w, h) in ((-0.6, 1.0, 0.8, 0.7, 0.35), (0.5, 1.6, 0.5, 0.6, 0.3), (0.2, 2.2, 0.6, 0.8, 0.32),
                            (-0.5, 2.6, 0.45, 0.5, 0.28)):
        for face in range(4):
            px, py = (x, -1.56) if face == 0 else (x, 1.56) if face == 1 else (-1.56, x) if face == 2 else (1.56, x)
            sx, sy = (w, 0.1) if face < 2 else (0.1, w)
            k.box(b, (px, py, y), (sx, sy, h), STONE_D, bevel=0.2)
    # 城垛（四边各两个，中间留缺口）
    for i in (-0.75, 0.75):
        k.box(b, (i, -1.45, 3.15), (0.5, 0.35, 0.5), STONE, bevel=0.15)
        k.box(b, (i, 1.45, 3.15), (0.5, 0.35, 0.5), STONE, bevel=0.15)
        k.box(b, (-1.45, i, 3.15), (0.35, 0.5, 0.5), STONE, bevel=0.15)
        k.box(b, (1.45, i, 3.15), (0.35, 0.5, 0.5), STONE, bevel=0.15)
    # 顶部木平台 + 木板缝
    k.box(b, (0, 0, 2.95), (2.6, 2.6, 0.12), WOOD, bevel=0.2)
    for i in (-0.65, 0.0, 0.65):
        k.box(b, (i, 0, 3.02), (0.06, 2.5, 0.03), WOOD_D, bevel=0)
    # 木门（拱顶）
    k.box(b, (0, -1.58, 0.85), (0.95, 0.12, 1.1), WOOD_D, bevel=0.1)
    k.cyl(b, (0, -1.58, 1.4), 0.475, 0.475, 0.12, WOOD_D, rot=(90, 0, 0), seg=14)
    k.box(b, (0, -1.66, 0.85), (0.08, 0.04, 1.0), WOOD, bevel=0)
    # 正面旗帜（阵营色）+ 金色王冠徽记 + 旗杆横杆
    k.box(b, (0, -1.62, 2.3), (1.0, 0.06, 1.25), TEAM, bevel=0.1, tag="team")
    k.box(b, (0, -1.64, 1.7), (1.0, 0.05, 0.08), GOLD, bevel=0.3)
    k.tube(b, [(-0.6, -1.66, 2.95), (0.6, -1.66, 2.95)], 0.04, WOOD_D)
    k.box(b, (0, -1.67, 2.4), (0.5, 0.04, 0.22), GOLD, bevel=0.2)
    for x in (-0.18, 0.0, 0.18):
        k.cyl(b, (x, -1.67, 2.6), 0.07, 0.0, 0.2, GOLD, rot=(90, 0, 0), seg=4, smooth=False)
    # 塔顶旗杆 + 阵营旗
    k.tube(b, [(0.9, 0.9, 3.0), (0.9, 0.9, 4.4)], 0.05, WOOD_D)
    k.box(b, (0.9, 0.55, 4.15), (0.06, 0.7, 0.45), TEAM, bevel=0.1, tag="team")
    k.sphere(b, (0.9, 0.9, 4.45), 0.08, GOLD)
