"""王国·牧场（ranch）：奶白谷仓 + 蓝色坡顶 + 山墙上木风车 + 木栅栏 + 奶牛 + 草垛。
原画：assets/kingdom_cartoon/ranch.png；侧背面为补全设计。
"""
import kbits as kb

B = kb.B
HAY = "#f2c84b"


def build(k):
    k.box(B, (0, 0, 0.08), (3.7, 3.3, 0.16), kb.GRASS, bevel=0.3)
    # 谷仓
    k.box(B, (0, 0.45, 0.9), (2.0, 1.6, 1.5), kb.CREAM, bevel=0.06)
    kb.gable(k, 0, 0.45, 1.6, 1.8, 2.3, 1.0, kb.BLUE, axis="y")
    for x in (-0.6, 0.6):
        k.box(B, (x, -0.38, 0.9), (0.12, 0.06, 1.4), kb.WOOD, bevel=0.2)
    kb.door(k, 0, -0.35, 0.16, 0.7, 1.05, color=kb.WOOD_D, frame=kb.WOOD)
    kb.window(k, 0, -0.38, 1.85, 0.3, 0.3)
    # 风车叶（山墙正面）
    k.cyl(B, (0, -0.55, 1.95), 0.12, 0.12, 0.15, kb.WOOD_D, rot=(90, 0, 0), seg=8)
    for a in (45, 135):
        k.box(B, (0, -0.62, 1.95), (2.2, 0.05, 0.36), "#f3ead7", rot=(0, a, 0), bevel=0.15)
        k.box(B, (0, -0.6, 1.95), (2.2, 0.06, 0.06), kb.WOOD_D, rot=(0, a, 0), bevel=0.3)
    # 栅栏（前方半圈）
    kb.fence(k, -1.7, 1.7, -1.5, 1.4, h=0.45, sides="swe", gap=("s", 0.0, 0.8))
    # 奶牛（左前）
    k.box(B, (-1.0, -0.9, 0.55), (0.75, 0.45, 0.45), "#f7f4ee", bevel=0.35)
    for (x, y, z) in ((-1.15, -1.12, 0.62), (-0.85, -0.68, 0.7)):
        k.sphere(B, (x, y, z), 0.13, "#2b2b2b", scale=(1.0, 0.4, 1.0))
    k.box(B, (-1.45, -0.95, 0.75), (0.3, 0.32, 0.3), "#f7f4ee", bevel=0.35)
    k.box(B, (-1.6, -0.95, 0.68), (0.12, 0.26, 0.15), "#f3b3b3", bevel=0.3)
    for y in (-1.06, -0.84):
        k.cyl(B, (-1.42, y, 0.95), 0.04, 0.0, 0.15, "#efe2c0", seg=6)
    for (x, y) in ((-1.25, -1.05), (-1.25, -0.75), (-0.75, -1.05), (-0.75, -0.75)):
        k.cyl(B, (x, y, 0.18), 0.07, 0.07, 0.36, "#f7f4ee", seg=8)
    # 草垛（右前）
    k.sphere(B, (1.1, -0.9, 0.4), 0.42, HAY, scale=(1.1, 1.0, 0.8))
    k.sphere(B, (1.4, -0.4, 0.32), 0.3, "#e6b93c", scale=(1.1, 1.0, 0.8))
