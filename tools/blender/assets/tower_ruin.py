"""塔废墟（3×3 格基准，王塔按占位放大复用）：开裂底座 + 高低错落的断墙 + 碎石堆 + 散落木板；敌我共用、不带阵营色。
原画：testAssets/新风格美术资源0830/战斗/箭塔 破.png。碎石位置为固定表（无随机，结果可复现）。
"""

STONE = "#cfc6b4"
STONE_D = "#a99f8c"
STONE_DD = "#857b69"
WOOD = "#9a6a3c"
SOOT = "#5e5850"


def build(k):
    b = "root"
    k.box(b, (0, 0, 0.12), (2.9, 2.9, 0.24), STONE_DD, bevel=0.3)
    k.box(b, (0, 0, 0.28), (2.5, 2.5, 0.12), SOOT, bevel=0.2)
    # 断墙：四条边各一段，高度不一，顶部斜断
    walls = (((0, -1.1), (2.3, 0.35, 0.9), 6), ((0, 1.1), (1.5, 0.35, 0.55), -4), ((-1.1, 0.3), (0.35, 1.7, 0.75), 5),
             ((1.1, -0.2), (0.35, 1.2, 0.4), -6))
    for (x, y), size, tilt in walls:
        k.box(b, (x, y, 0.3 + size[2] * 0.5), size, STONE, rot=(tilt if size[0] > 1 else 0, tilt if size[1] > 1 else 0, 0),
              bevel=0.15)
    for x, y, h in ((-1.15, -1.15, 1.25), (1.15, -1.15, 0.7), (-1.15, 1.15, 0.6), (1.15, 1.15, 0.95)):
        k.box(b, (x, y, 0.3 + h * 0.5), (0.5, 0.5, h), STONE_D, rot=(0, 0, 8), bevel=0.15)
    # 碎石堆（固定表）
    rubble = ((-0.3, -0.2, 0.22), (0.25, 0.1, 0.18), (0.05, 0.45, 0.2), (-0.55, 0.35, 0.15), (0.6, -0.4, 0.16),
              (0.3, 0.6, 0.14), (-0.1, -0.6, 0.17), (0.75, 0.3, 0.13), (-0.7, -0.5, 0.15), (0.0, 0.05, 0.26))
    for i, (x, y, r) in enumerate(rubble):
        k.box(b, (x, y, 0.32 + r * 0.5), (r * 2.2, r * 1.8, r * 1.4), STONE_D if i % 2 else STONE,
              rot=(i * 13, i * 7, i * 29), bevel=0.25)
    # 散落木板
    for x, y, a in ((-0.2, 0.25, 30), (0.4, -0.15, -55), (-0.45, -0.3, 80)):
        k.box(b, (x, y, 0.42), (1.0, 0.16, 0.06), WOOD, rot=(0, 8, a), bevel=0.2)
