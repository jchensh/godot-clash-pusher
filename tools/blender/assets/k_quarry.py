"""王国·采石场（quarry）：灰色岩山 + 木框矿洞口 + 左侧木吊架与吊桶 + 前方散落石块。
原画：assets/kingdom_cartoon/quarry.png；侧背面为补全设计。
"""
import kbits as kb

B = kb.B
ROCK = "#9aa0a8"
ROCK_D = "#7c8189"
ROCK_L = "#b8bdc4"


def build(k):
    k.box(B, (0, 0, 0.08), (3.6, 3.0, 0.16), "#b9b08f", bevel=0.35)
    k.sphere(B, (0.2, 0.4, 0.9), 1.45, ROCK, scale=(1.1, 0.9, 0.85), seg=10, rings=7)
    k.sphere(B, (-0.6, 0.7, 1.35), 0.9, ROCK_D, scale=(1.0, 0.9, 1.0), seg=9, rings=6)
    k.sphere(B, (0.9, 0.2, 1.5), 0.75, ROCK_L, scale=(1.0, 0.9, 1.1), seg=9, rings=6)
    k.sphere(B, (0.2, 0.6, 2.0), 0.6, ROCK_L, seg=8, rings=6)
    # 矿洞口：木框 + 黑洞 + 木门
    k.box(B, (0.35, -0.85, 0.6), (1.05, 0.5, 1.15), ROCK_D, bevel=0.15)
    k.box(B, (0.35, -1.12, 0.55), (0.75, 0.08, 0.95), kb.DARK, bevel=0.05)
    k.box(B, (0.35, -1.16, 0.45), (0.6, 0.06, 0.75), kb.WOOD, bevel=0.1)
    for x in (-0.12, 0.82):
        k.box(B, (x, -1.17, 0.6), (0.14, 0.14, 1.2), kb.WOOD_D, bevel=0.2)
    k.box(B, (0.35, -1.17, 1.22), (1.15, 0.16, 0.16), kb.WOOD_D, bevel=0.2)
    # 木吊架 + 吊桶（左）
    k.box(B, (-1.3, -0.3, 1.0), (0.14, 0.14, 2.0), kb.WOOD_D, bevel=0.2)
    k.box(B, (-0.85, -0.3, 1.95), (1.0, 0.12, 0.12), kb.WOOD_D, bevel=0.2)
    k.tube(B, [(-1.3, -0.3, 1.4), (-0.9, -0.3, 1.9)], 0.04, kb.WOOD_D)
    k.tube(B, [(-0.45, -0.3, 1.95), (-0.45, -0.3, 1.35)], 0.02, "#6a6a6a")
    k.cyl(B, (-0.45, -0.3, 1.15), 0.28, 0.2, 0.4, "#5b5f66", seg=10)
    # 散落石块
    for (x, y, s, a) in ((-1.2, -1.15, 0.45, 15), (-0.55, -1.35, 0.35, -20), (1.3, -1.1, 0.4, 30),
                         (1.45, -0.4, 0.32, -10), (-1.5, 0.6, 0.38, 5)):
        k.box(B, (x, y, s * 0.4), (s, s * 0.8, s * 0.75), ROCK_L, rot=(0, 0, a), bevel=0.25)
